// ---------- Service worker (root scope) ----------
let swReg = null;
if ("serviceWorker" in navigator) {
  navigator.serviceWorker
    .register("/sw.js", { scope: "/" })
    .then((reg) => {
      swReg = reg;
    })
    .catch(() => {});
}

// ---------- iOS "Add to Home Screen" prompt ----------
// Rules: iOS Safari only, not when already installed, remember dismissal
// for a cooldown period so it isn't shown on every load.
const DISMISS_KEY = "iosInstallDismissedUntil";
const DISMISS_DAYS = 7;

function isIos() {
  const ua = window.navigator.userAgent;
  const iDevice = /iPad|iPhone|iPod/.test(ua);
  const iPadOs = navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1;
  return iDevice || iPadOs;
}

function isStandalone() {
  return (
    window.navigator.standalone === true ||
    window.matchMedia("(display-mode: standalone)").matches
  );
}

function dismissedRecently() {
  try {
    const until = Number(localStorage.getItem(DISMISS_KEY) || 0);
    return Date.now() < until;
  } catch {
    return false;
  }
}

function rememberDismissal() {
  try {
    localStorage.setItem(
      DISMISS_KEY,
      String(Date.now() + DISMISS_DAYS * 24 * 60 * 60 * 1000)
    );
  } catch {}
}

function maybeShowIosInstall() {
  if (!isIos() || isStandalone() || dismissedRecently()) return;
  const el = document.getElementById("ios-install");
  const close = document.getElementById("ios-install-close");
  if (!el) return;

  el.hidden = false;
  const hide = () => {
    el.hidden = true;
    rememberDismissal();
  };
  close.addEventListener("click", hide);
  el.addEventListener("click", (e) => {
    if (e.target === el) hide();
  });
}

maybeShowIosInstall();

// ---------- Local notifications every 10 minutes ----------
// Generated by the app itself (no push server). Requires the user to grant
// permission; on iOS this only works once the PWA is installed to Home Screen.
const NOTIFY_INTERVAL_MS = 10 * 60 * 1000; // 10 minutes
const notifBtn = document.getElementById("notif-btn");

function notifyOnce() {
  const payload = {
    type: "NOTIFY",
    title: "Incubator",
    body: "Don't forget to check your equipment.",
  };
  if (swReg && swReg.active) {
    swReg.active.postMessage(payload);
  } else if (navigator.serviceWorker && navigator.serviceWorker.controller) {
    navigator.serviceWorker.controller.postMessage(payload);
  }
}

function startNotifyLoop() {
  notifyOnce(); // fire one immediately so the user sees it works
  setInterval(notifyOnce, NOTIFY_INTERVAL_MS);
}

function setupNotifications() {
  if (!("Notification" in window)) return;

  if (Notification.permission === "granted") {
    startNotifyLoop();
    return;
  }
  if (Notification.permission === "denied") return;

  // Need to ask — show a button (permission must be requested from a user gesture).
  if (notifBtn) {
    notifBtn.classList.remove("d-none");
    notifBtn.addEventListener("click", async () => {
      const perm = await Notification.requestPermission();
      if (perm === "granted") {
        notifBtn.classList.add("d-none");
        startNotifyLoop();
      }
    });
  }
}

setupNotifications();
